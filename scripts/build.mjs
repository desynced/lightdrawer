// Build: inline the core libs into public/app.js (receipt maker) and a single-file
// public/verify.html (offline verifier). No bundler, no dependencies.
import { readFileSync, writeFileSync, readdirSync, mkdirSync, existsSync, copyFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const rd = (p) => readFileSync(join(root, p), 'utf8');
const pemDer = (pem) => Buffer.from(pem.replace(/-----(BEGIN|END)[^-]+-----/g, '').replace(/\s+/g, ''), 'base64');
const rootPem = rd('trust/freetsa-cacert.pem'), tsaPem = rd('trust/freetsa-tsa.crt'), rekorPem = rd('trust/rekor.sigstore.dev.pub');
const rootSha256 = createHash('sha256').update(pemDer(rootPem)).digest('hex');
let ctLogs = [];
try { ctLogs = JSON.parse(rd('trust/ct-logs.json')).logs || []; } catch { /* optional snapshot */ }
const isrgRoots = [];
for (const f of ['isrg-root-x1.pem', 'isrg-root-x2.pem']) {
  try { isrgRoots.push({ name: f, pem: rd('trust/' + f) }); } catch { /* optional */ }
}
const trustJs = `/* Generated by scripts/build.mjs from trust/. Pinned trust anchors. */
const TRUST = ${JSON.stringify({ rootPem, rootSha256, tsaCertPem: tsaPem, rekorPubPem: rekorPem, ctLogs, isrgRoots }, null, 1)};
const TRUST_FILES = { 'freetsa-cacert.pem': utf8(TRUST.rootPem), 'freetsa-tsa.crt': utf8(TRUST.tsaCertPem), 'rekor.sigstore.dev.pub': utf8(TRUST.rekorPubPem) };
`;
const libs = readdirSync(join(root, 'web/lib')).filter((f) => f.endsWith('.js')).sort();
const core = libs.map((f) => `/* ---- ${f} ---- */\n` + rd('web/lib/' + f)).join('\n') + '\n' + trustJs;
mkdirSync(join(root, 'build'), { recursive: true });
mkdirSync(join(root, 'public'), { recursive: true });
writeFileSync(join(root, 'build/core.js'), core);
if (existsSync(join(root, 'web/ui/verify.html'))) {
  const html = rd('web/ui/verify.html').replace('<!--CORE-->', () => `<script>\n${core}\n${rd('web/ui/verify-ui.js')}\n</script>`);
  if (html.includes('</script') && /<\/script[^>]*>[\s\S]*<\/script/.test(core)) throw new Error('core contains </script>');
  writeFileSync(join(root, 'public/verify.html'), html);
}
if (existsSync(join(root, 'web/ui/index.html'))) {
  const stampLink = rd('src/stamp-link.js').replace(/^export /gm, '');
  writeFileSync(join(root, 'public/app.js'), `'use strict';\n${core}\n${stampLink}\n${rd('web/ui/maker.js')}\n`);
  writeFileSync(join(root, 'public/index.html'), rd('web/ui/index.html'));
  writeFileSync(join(root, 'public/style.css'), rd('web/ui/style.css'));
  writeFileSync(join(root, 'public/_headers'), rd('web/ui/_headers'));
  writeFileSync(join(root, 'public/404.html'), rd('web/ui/404.html'));
  // Brand / static assets (logo, favicons, OG image)
  const brandAssets = [
    'logo.svg', 'logo-lockup.svg', 'favicon.svg', 'favicon-16.svg', 'favicon-16.png',
    'favicon-32.png', 'apple-touch-icon.png', 'og-image.png',
  ];
  for (const f of brandAssets) {
    const src = join(root, 'web/ui', f);
    if (existsSync(src)) copyFileSync(src, join(root, 'public', f));
  }
  for (const f of ['button.html', 'button.js']) {
    const src = join(root, 'web/ui', f);
    if (existsSync(src)) copyFileSync(src, join(root, 'public', f));
  }
  const examplesDir = join(root, 'web/ui/examples');
  if (existsSync(examplesDir)) {
    mkdirSync(join(root, 'public/examples'), { recursive: true });
    for (const f of readdirSync(examplesDir).filter((n) => n.endsWith('.html'))) {
      copyFileSync(join(examplesDir, f), join(root, 'public/examples', f));
    }
  }
  const stampHelper = join(root, 'web/snippets/lightdrawer-stamp.js');
  if (existsSync(stampHelper)) copyFileSync(stampHelper, join(root, 'public/lightdrawer-stamp.js'));
  const securityTxt = join(root, 'web/ui/.well-known/security.txt');
  if (existsSync(securityTxt)) {
    mkdirSync(join(root, 'public/.well-known'), { recursive: true });
    copyFileSync(securityTxt, join(root, 'public/.well-known/security.txt'));
  }
}
console.log(`built: ${libs.length} libs, root pin ${rootSha256}`);
